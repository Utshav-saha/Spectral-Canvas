/** Width in pixels of `text` once set, trailing advance removed. */
export function textWidth(text) {
  return text.length === 0 ? 0 : text.length * ADVANCE - 1
}

/**
 * Stamp `text` at (x, y) as solid pixels. Never call fillText on this canvas:
 * the whole screen is a four-tone panel and antialiasing would invent tones.
 */
export function drawText(ctx, text, x, y, color) {
  ctx.fillStyle = color
  const chars = String(text).toUpperCase()
  for (let i = 0; i < chars.length; i++) {
    const rows = F[chars[i]] ?? F[chars[i].toLowerCase()] ?? F['?']
    const ox = x + i * ADVANCE
    for (let r = 0; r < GLYPH_H; r++) {
      const bits = rows[r]
      if (!bits) continue
      for (let c = 0; c < GLYPH_W; c++) {
        if (bits & (1 << (GLYPH_W - 1 - c))) ctx.fillRect(ox + c, y + r, 1, 1)
      }
    }
  }
}
